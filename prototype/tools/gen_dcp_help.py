"""Generate pydyn/dcp_help.py from Dynamo 1.1.514's detailed parameter help (run once; the output is checked in).

  python -I prototype/tools/gen_dcp_help.py [/programs/.../1.1.514/matlab/src] > prototype/pydyn/dcp_help.py

S/dynamo__help_parameters.m ("Automatically created by devpack.helpfiles.createBigHelpFileForProjectParameters")
holds, for 100 project parameters, the help lines that Dynamo prints with dynamo_vpr_help(<name>) (S/dynamo_vpr_help.m:68)
and in the temporal head (S/dynamo_temporal_head.m:1009). The dcp rounds window itself shows only the parameter's
short comment (S/dynamo__wizard_rounds.m:261-281); pyDynamo's window shows that comment and, under it, these lines.
Every line of the source is `infolines{end+1}='...';` inside `case '<name>'` blocks; the text is kept verbatim.
tests/test_dcpgui.py re-parses the source (when present) and compares it with the checked-in table.
"""
import os
import re
import sys

SRC = "/programs/x86_64-linux/dynamo/1.1.514/matlab/src"
_CASE = re.compile(r"^\s*case\s+'([^']+)'\s*$")
_LINE = re.compile(r"^\s*infolines\{end\+1\}='(.*)';\s*$")


def parse_help(src=SRC):
    """{parameter name: tuple of help lines} of S/dynamo__help_parameters.m, verbatim ('' -> ' as in MATLAB)."""
    out, name = {}, None
    with open(os.path.join(src, "dynamo__help_parameters.m"), encoding="latin-1") as f:
        for line in f:
            m = _CASE.match(line)
            if m:
                name = m.group(1)
                out[name] = []
                continue
            m = _LINE.match(line)
            if m and name is not None:
                out[name].append(m.group(1).replace("''", "'"))
    return {k: tuple(v) for k, v in out.items()}


def main(argv):
    src = argv[1] if len(argv) > 1 else SRC
    h = parse_help(src)
    print('"""Dynamo 1.1.514\'s detailed help of the project parameters, verbatim: S/dynamo__help_parameters.m, the lines')
    print("that Dynamo prints with dynamo_vpr_help(<name>). Generated by prototype/tools/gen_dcp_help.py; do not edit.")
    print('"""')
    print()
    print("HELP = {")
    for k in sorted(h, key=str.lower):
        print("    %r: (" % k)
        for line in h[k]:
            print("        %r," % line)
        print("    ),")
    print("}")


if __name__ == "__main__":
    main(sys.argv)
