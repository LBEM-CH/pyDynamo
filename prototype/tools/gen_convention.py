"""Generate pydyn/convention.py from Dynamo 1.1.514's dynamo_vpr_convention.m (run once; the output is checked in).

  python -I prototype/tools/gen_convention.py [/programs/.../1.1.514/matlab/src/dynamo_vpr_convention.m] > prototype/pydyn/convention.py

tests/test_stage3_vpr.py re-parses the source (when it is present) and compares it with the checked-in table.
"""
import os
import pprint
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from pydyn.convention_parse import parse_convention, SOURCE  # noqa: E402

src = sys.argv[1] if len(sys.argv) > 1 else SOURCE
nc, rc = parse_convention(src)
print('"""Parameter convention of Dynamo 1.1.514: dynamo_vpr_convention.m, generated by prototype/tools/gen_convention.py.')
print("")
print("NC = the 44 global parameters (cell 'nc'), RC = the 53 round parameters (cell 'rc'), both in file order.")
print("Each entry: name, type (0 char, 1 numeric, 2 boolean, 3 char plugin/flags, 6 numeric-or-code), value (default:")
print("str, float, tuple of floats for a numeric vector, bool for MATLAB false/true), hidden, short, pretty, comment,")
print("advanced, area, options, line (line of '.name' in the source). Do not edit by hand.")
print('"""')
print("SOURCE_VERSION = '1.1.514'")
print("NC = " + pprint.pformat(nc, width=118, sort_dicts=False))
print("RC = " + pprint.pformat(rc, width=118, sort_dicts=False))
