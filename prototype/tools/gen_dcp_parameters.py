"""Generate pydyn/dcp_parameters.py from Dynamo 1.1.514's GUI parameter classes (run once; the output is checked in).

  python -I prototype/tools/gen_dcp_parameters.py [/programs/.../1.1.514/matlab/src] > prototype/pydyn/dcp_parameters.py

The dcp windows do not use dynamo_vpr_convention.m for labels, areas and types: they build one object per parameter
from S/+dpkproject/+parameters/+list/@<name>/<name>.m (dProject.setFromVpr, runtimeRoundPublish,
parameterGUIEditCallback). Those class files differ from the convention for some parameters (e.g. the area of
update_with_unweighted_average is 'correlation' there and 'averaging' in the convention), so the GUI needs this table.
tests/test_dcpgui.py re-parses the source (when present) and compares it with the checked-in table.
"""
import os
import pprint
import re
import sys

SRC = "/programs/x86_64-linux/dynamo/1.1.514/matlab/src"
_FIELDS = ("type", "name", "functionality", "short", "default", "advanced", "pretty", "comment")


def _matlab_str(s):
    s = s.strip()
    if not (s.startswith("'") and s.endswith("'")):
        raise ValueError("not a MATLAB string: %r" % s)
    return s[1:-1].replace("''", "'")


def parse_class(path):
    """{'type','name','functionality','short','default','advanced','pretty','comment','round','line'} of one
    @<name>/<name>.m constructor (lines 'obj.<field> = <value>;')."""
    txt = open(path, encoding="latin-1").read()
    head = txt.split("\n", 1)[0]
    out = {"round": "roundLocator" in head}
    for i, ln in enumerate(txt.split("\n"), 1):
        m = re.match(r"\s*obj\.(\w+)\s*=\s*(.*?);\s*(%.*)?$", ln)
        if not m or m.group(1) not in _FIELDS or m.group(1) in out:
            continue
        k, v = m.group(1), m.group(2).strip()
        if k in ("type", "advanced"):
            out[k] = int(float(v))
        elif k == "default":
            out[k] = v                                # MATLAB literal, kept as text (the vpr default is the convention's)
        else:
            out[k] = _matlab_str(v)
        if k == "name":
            out["line"] = i
    return out


def parse_all(src=SRC):
    base = os.path.join(src, "+dpkproject", "+parameters", "+list")
    out = {}
    for d in sorted(os.listdir(base)):
        n = d[1:]
        f = os.path.join(base, d, n + ".m")
        if d.startswith("@") and os.path.isfile(f):
            p = parse_class(f)
            if p.get("name") != n:
                raise ValueError("%s: obj.name %r" % (f, p.get("name")))
            out[n] = p
    return out


if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else SRC
    table = parse_all(src)
    print('"""dcp GUI parameter classes of Dynamo 1.1.514 (+dpkproject/+parameters/+list/@<name>/<name>.m), generated by')
    print("prototype/tools/gen_dcp_parameters.py. Do not edit by hand.")
    print("")
    print("PARAMETERS[name] = type, name, functionality (the area check boxes of the rounds window), short, default (MATLAB")
    print("text), advanced, pretty (row label), comment, round (roundLocator subclass), line.")
    print('"""')
    print("SOURCE_VERSION = '1.1.514'")
    print("PARAMETERS = " + pprint.pformat(table, width=118, sort_dicts=False))
